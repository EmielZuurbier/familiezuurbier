import type { Family, Person } from './types'
function person(
  id: string,
  name: string,
  year?: number,
  lifeStatus: Person['lifeStatus'] = 'unknown',
  deathYear?: number,
): Person {
  return {
    id,
    name,
    birth: { year },
    birthPlace: 'Voorbeelddorp',
    lifeStatus,
    death: { year: deathYear },
  }
}
